
package com.mdpgroup08.scpd.ui.club

import androidx.compose.foundation.Image
import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.aspectRatio
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.Button
import androidx.compose.material3.Card
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.asImageBitmap
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.unit.dp
import com.mdpgroup08.scpd.data.qr.CheckInQrGenerator
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

@Composable
fun CheckInQrScreen(
    eventId: String,
    onBack: () -> Unit
) {
    var codeCounter by remember(eventId) {
        mutableStateOf(1L)
    }

    var generated by remember(eventId) {
        mutableStateOf(
            CheckInQrGenerator.generate(eventId, 1L)
        )
    }

    val qrCode = generated.first
    val qrBitmap = generated.second

    val expiryText = remember(qrCode.expiresAt) {
        SimpleDateFormat(
            "EEE d MMM, h:mm a",
            Locale.getDefault()
        ).format(Date(qrCode.expiresAt))
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(24.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp),
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Row(
            modifier = Modifier.fillMaxWidth(),
            horizontalArrangement = Arrangement.Start
        ) {
            TextButton(onClick = onBack) {
                Text("Back to My Events")
            }
        }

        Text(
            text = "Event Check-in QR",
            style = MaterialTheme.typography.headlineSmall
        )

        Text(
            text = "Event ID: $eventId",
            style = MaterialTheme.typography.bodyMedium
        )

        Card(
            modifier = Modifier
                .fillMaxWidth()
                .aspectRatio(1f)
        ) {
            Image(
                bitmap = qrBitmap.asImageBitmap(),
                contentDescription = "Event check-in QR code",
                modifier = Modifier
                    .fillMaxSize()
                    .padding(16.dp),
                contentScale = ContentScale.Fit
            )
        }

        Text(
            text = "QR code expires at $expiryText",
            style = MaterialTheme.typography.bodyMedium
        )

        Text(
            text = "QR counter: $codeCounter",
            style = MaterialTheme.typography.bodySmall
        )

        Button(
            onClick = {
                codeCounter += 1L
                generated = CheckInQrGenerator.generate(
                    eventId,
                    codeCounter
                )
            },
            modifier = Modifier.fillMaxWidth()
        ) {
            Text("Generate New QR Code")
        }

        Text(
            text = "Prototype only: QR signature verification is not yet implemented. Do not use this version for real attendance validation.",
            color = MaterialTheme.colorScheme.error,
            style = MaterialTheme.typography.bodySmall
        )
    }
}
